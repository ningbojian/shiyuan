from __future__ import annotations

from django.contrib.auth import get_user_model
from django.core.exceptions import ValidationError
from django.db import IntegrityError, transaction
from django.test import TestCase

from Surname.models import Clan, Distribution, Province, SecondName, SurnameRelation
from user.models import Favorite, ReadingHistory


class SecondNameModelTests(TestCase):
    def test_slug_autogenerated(self):
        surname = SecondName.objects.create(second_name="李", pinyin="li")
        self.assertEqual(surname.slug, "li")
        self.assertEqual(surname.initial, "L")

    def test_duplicate_slug_gets_suffix(self):
        SecondName.objects.create(second_name="李", pinyin="li")
        duplicate = SecondName.objects.create(second_name="黎", pinyin="li")
        self.assertEqual(duplicate.slug, "li-2")

    def test_keywords_validation(self):
        surname = SecondName.objects.create(second_name="李", pinyin="li")
        surname.keywords = "not-a-list"
        with self.assertRaises(ValidationError):
            surname.full_clean()

        surname.keywords = [{"name": "陇西", "value": 40}]
        surname.full_clean()

        surname.keywords = [{"name": "陇西", "value": 0}]
        with self.assertRaises(ValidationError):
            surname.full_clean()

    def test_view_count_default(self):
        surname = SecondName.objects.create(second_name="李", pinyin="li")
        self.assertEqual(surname.view_count, 0)

    def test_is_imported_defaults_false(self):
        surname = SecondName.objects.create(second_name="李", pinyin="li")
        self.assertFalse(surname.is_imported)


class DistributionModelTests(TestCase):
    def setUp(self):
        self.surname = SecondName.objects.create(second_name="李", pinyin="li")
        self.province = Province.objects.create(name="河北省", slug="hebei")

    def test_distribution_unique_pair(self):
        Distribution.objects.create(surname=self.surname, province=self.province)
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                Distribution.objects.create(surname=self.surname, province=self.province)

    def test_intensity_range(self):
        distribution = Distribution(
            surname=self.surname, province=self.province, intensity=101
        )
        with self.assertRaises(ValidationError):
            distribution.full_clean()


class RelationModelTests(TestCase):
    def setUp(self):
        self.surname = SecondName.objects.create(second_name="李", pinyin="li")
        self.target = SecondName.objects.create(second_name="赵", pinyin="zhao")
        self.clan = Clan.objects.create(name="嬴姓", slug="ying-xing", kind="xing")

    def test_relation_requires_exactly_one_target(self):
        relation = SurnameRelation(
            source=self.surname,
            target_surname=self.target,
            target_clan=self.clan,
            relation_type="branch",
        )
        with self.assertRaises(ValidationError):
            relation.full_clean()

        relation = SurnameRelation(source=self.surname, relation_type="branch")
        with self.assertRaises(ValidationError):
            relation.full_clean()

        relation = SurnameRelation(
            source=self.surname,
            target_surname=self.target,
            relation_type="branch",
        )
        relation.full_clean()


