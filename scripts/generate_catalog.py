def build_surname(surname: str) -> dict:
    clan = ORIGIN_CLAN[surname]
    regions = REGIONS[surname]
    figures = FIGURES[surname]

    text = generated_text(surname, clan, regions, figures)
    text.update({key: value for key, value in source_text(surname).items() if value})

    keywords = [
        {"name": f"{surname}姓", "value": 100},
        {"name": figures[0][0], "value": 90},
        {"name": figures[1][0], "value": 80},
    ]
    for index, region in enumerate(regions[:5]):
        keywords.append({"name": f"{region}地区", "value": 70 - index * 8})

    distributions = []
    for index, region in enumerate(regions):
        distributions.append(
            {
                "province": PROVINCE_MAP[region],
                "intensity": max(12, 80 - index * 7),
                "is_illustrative": True,
                "source_note": "示意强度，非人口占比。",
            }
        )

    figure_items = []
    for index, (name, dynasty, birth_year, death_year, info) in enumerate(figures):
        figure_items.append(
            {
                "name": name,
                "slug": figure_slug(name),
                "dynasty": dynasty,
                "info": info,
                "birth_year": birth_year,
                "death_year": death_year,
                "source_note": CHILD_NOTE,
                "is_demo": True,
                "order": index,
            }
        )

    event_items = []
    for index, (dynasty, from_region, to_region, description) in enumerate(
        EVENTS[surname], start=1
    ):
        event_items.append(
            {
                "dynasty": dynasty,
                "from_province": PROVINCE_MAP[from_region],
                "to_province": PROVINCE_MAP[to_region],
                "description": description,
                "source_note": CHILD_NOTE,
                "order": index,
            }
        )

    relations = [
        {
            "target_clan": clan,
            "relation_type": "origin",
            "description": f"{surname}姓的一支源流与{clan}有关。",
            "source_note": CHILD_NOTE,
        }
    ]
    for extra in EXTRA_RELATIONS.get(surname, []):
        relations.append({**extra, "source_note": CHILD_NOTE})

    return {
        "second_name": surname,
        "slug": pinyin(surname),
        "pinyin": pinyin(surname),
        "initial": pinyin(surname)[0].upper(),
        "aliases": [f"{surname}氏"],
        "summary": text["summary"],
        "base_information": text["base_information"],
        "ori": text["ori"],
        "mig": text["mig"],
        "dis": text["dis"],
        "cul": text["cul"],
        "fam": text.get("fam", ""),
        "keywords": keywords,
        "source_note": SOURCE_NOTE,
        "is_demo": True,
        "is_imported": False,
        "is_featured": surname in {"李", "王", "张", "刘", "陈", "杨"},
        "popularity": 100 - SURNAMES.index(surname),
        "figures": figure_items,
        "distributions": distributions,
        "migration_events": event_items,
        "relations": relations,
    }


def build_surnames(source_dir: Path | None) -> tuple[list[dict], dict]:
    """Build curated entries and merge the optional course archive."""
    curated = [build_surname(surname) for surname in SURNAMES]
    if source_dir is None:
        return curated, {
            "added": 0,
            "merged": 0,
            "figures_added": 0,
            "figures_deduped": 0,
        }

    used_slugs = {item["slug"] for item in curated}
    imported = []
    for source in scan_source_dir(source_dir):
        pinyin_value, initial = pinyin_for_surname(source.name)
        slug = slug_for_surname(source.name, used_slugs)
        imported.append(
            build_imported_entry(
                source,
                slug=slug,
                pinyin=pinyin_value,
                initial=initial,
            )
        )
    return merge_catalog(curated, imported)


