def pinyin(text: str) -> str:
    return "".join(lazy_pinyin(text)).lower()


def figure_slug(name: str) -> str:
    return "-".join(lazy_pinyin(name)).lower()


def source_text(surname: str) -> dict[str, str]:
    values = {}
    folder = SOURCE_DIR / surname
    for filename, field in SOURCE_FIELDS.items():
        path = folder / filename
        if path.exists():
            values[field] = path.read_text(encoding="utf-8-sig").strip()
    return values


